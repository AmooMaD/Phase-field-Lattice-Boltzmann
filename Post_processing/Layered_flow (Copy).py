# ============================================================
# Read numerical data
# ============================================================

Fakhari = np.loadtxt(StringIO(data_Fakhari), skiprows=1)

arc_Fakhari = Fakhari[:, 0]
velocity_Fakhari = Fakhari[:, 1]


Liang = np.loadtxt(StringIO(data_Liang), skiprows=1)

arc_Liang = Liang[:, 0]
velocity_Liang = Liang[:, 1]


HCZ = np.loadtxt(StringIO(data_HCZ), skiprows=1)

arc_HCZ = HCZ[:, 0]
velocity_HCZ = HCZ[:, 1]

# ============================================================
# Analytical parameters
# ============================================================

a = 0.4          # Half-width of non-wetting layer
b = 1.0          # Half channel height

mu_w = 1
M = 1.0
mu_nw = M * mu_w

Fx = 2.5e-5

# ============================================================
# Analytical solution
# ============================================================

y = np.linspace(-b, b, 99)
u = np.zeros_like(y)

wetting = np.abs(y) >= a
nonwetting = np.abs(y) < a

u[wetting] = (Fx/(2*mu_w))*(b**2 - y[wetting]**2)

u_interface = (Fx/(2*mu_w))*(b**2 - a**2)

u[nonwetting] = (
    u_interface
    + (Fx/(2*mu_nw))*(a**2 - y[nonwetting]**2)
)

# ============================================================
# Normalization
# ============================================================

# Arc length --> [-b,b]
y_num = (arc_Fakhari - arc_Fakhari.min())/(arc_Fakhari.max()-arc_Fakhari.min())*(2*b) - b



# Normalize by analytical maximum velocity
u_max_analytical = np.max(u)

u_analytical = u / u_max_analytical
u_Fakhari = velocity_Fakhari / u_max_analytical
u_Liang = velocity_Liang / u_max_analytical
u_HCZ = velocity_HCZ / u_max_analytical


# ============================================================
# Error relative to analytical solution
# ============================================================

u_analytical_num = np.interp(y_num, y, u_analytical)

error_Fakhari = np.linalg.norm(u_Fakhari - u_analytical_num) / np.linalg.norm(u_analytical_num)
error_Liang   = np.linalg.norm(u_Liang   - u_analytical_num) / np.linalg.norm(u_analytical_num)
error_HCZ     = np.linalg.norm(u_HCZ     - u_analytical_num) / np.linalg.norm(u_analytical_num)

print("\n==============================================")
print("Relative L2 error with respect to analytical solution")
print("==============================================")
print(f"Fakhari et al. : {error_Fakhari:.6e}  ({error_Fakhari*100:.4f} %)")
print(f"Liang et al.   : {error_Liang:.6e}  ({error_Liang*100:.4f} %)")
print(f"HCZ            : {error_HCZ:.6e}  ({error_HCZ*100:.4f} %)")
print("==============================================\n")




